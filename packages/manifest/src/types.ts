/** CSS `font-display` values. Same as the DOM's `FontDisplay`, so the types work without the DOM lib. */
export type FontDisplay = "auto" | "block" | "fallback" | "optional" | "swap";

/** A self-hosted font file plus the FontFace descriptors that select it. */
export interface FontSource {
  /** The `font-family` name the face is registered under. */
  family: string;
  /** URL of the font file (woff2 recommended), a CSS `src` value, or a list of fallbacks. */
  src: string | readonly string[];
  /** A number, a keyword, or a range for variable fonts (`"100 900"`). */
  weight?: string | number;
  style?: string;
  stretch?: string;
  unicodeRange?: string;
  /** Defaults to `"swap"`. */
  display?: FontDisplay;
}

/**
 * Everything inktrap knows about one font family. Generated by `@inktrapjs/cli` or
 * `@inktrapjs/vite`, or written by hand: only `family` and `faces` are required.
 *
 * Compatibility: new fields are only ever added as optional, and readers must ignore
 * fields they don't know. `schemaVersion` changes only for a breaking change.
 */
export interface FontManifest {
  /** Format version. Absent means `1`. Generated manifests always set it. */
  schemaVersion?: 1;
  /** Typographic family name (OpenType name ID 16, falling back to ID 1). */
  family: string;
  /** Font files of the family. Every face's `family` should equal `family`. */
  faces: FontSource[];
  /** Font version string (name ID 5), e.g. `"Version 1.008"`. */
  version?: string;
  /** Designer names (name ID 9). */
  designers?: string[];
  /** Designer URL (name ID 12). */
  designerUrl?: string;
  /** Copyright notice (name ID 0). */
  copyright?: string;
  license?: FontLicense;
  metrics?: FontMetrics;
  /** Variation axes, merged across faces. Absent or empty for static fonts. */
  axes?: FontAxis[];
  /** Named instances (`fvar`), e.g. "Bold" or "Black Italic". */
  instances?: FontInstance[];
  /** OpenType layout features (GSUB and GPOS) available in at least one face. */
  features?: FontFeature[];
  /**
   * Reserved for glyph data (planned for v0.3). It lives in a separate file so that
   * manifests stay small and glyph lists load only on pages that show them.
   */
  glyphs?: FontGlyphsRef;
}

export interface FontLicense {
  /** License description (name ID 13), e.g. `"SIL Open Font License, Version 1.1"`. */
  name?: string;
  /** License URL (name ID 14). */
  url?: string;
}

/** Vertical metrics in font units. Divide by `unitsPerEm` to get ems. */
export interface FontMetrics {
  unitsPerEm: number;
  /** Typographic ascender (positive). */
  ascender?: number;
  /** Typographic descender (usually negative). */
  descender?: number;
  lineGap?: number;
  xHeight?: number;
  capHeight?: number;
}

export interface FontAxis {
  /** Four-character axis tag, e.g. `"wght"` or `"SOFT"`. */
  tag: string;
  /** Human-readable name from the font, e.g. `"Weight"`. */
  name?: string;
  min: number;
  default: number;
  max: number;
  /** The font asks for this axis to be hidden from user interfaces. */
  hidden?: boolean;
}

export interface FontInstance {
  /** Subfamily name, e.g. `"Semibold Italic"`. */
  name: string;
  /** Axis values by tag, e.g. `{ wght: 600, opsz: 72 }`. */
  coordinates: Record<string, number>;
  postScriptName?: string;
  /** The `style` of the face this instance belongs to, when not `"normal"`. */
  style?: string;
}

export interface FontFeature {
  /** Four-character feature tag, e.g. `"ss01"`. */
  tag: string;
  /**
   * Name provided by the font itself (stylistic set and character variant names).
   * For standard labels such as "Tabular numbers", see `@inktrapjs/manifest/features`.
   */
  name?: string;
}

/** Pointer to a separately loaded glyph data file. The file's format is not defined yet. */
export interface FontGlyphsRef {
  /** URL of the glyph data file. */
  src: string;
}
